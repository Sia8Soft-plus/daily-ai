const { app, BrowserWindow, shell, nativeImage } = require('electron');
const {badgePng}=require('../main/taskbar-badge');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const { execFile } = require('node:child_process');
const { promisify } = require('node:util');
const { APP_ID, LEGACY_APP_ID, cacheShellIcon, repairExistingShortcuts } = require('../main/windows-shell');

const root = fs.mkdtempSync(path.join(os.tmpdir(),'daily-ai-shell-test-'));
app.setPath('userData',path.join(root,'profile'));
app.on('window-all-closed',()=>{});
app.whenReady().then(async () => {
  const badgeWindow=new BrowserWindow({show:false});
  for(const count of [1,12,100]){const icon=nativeImage.createFromBuffer(badgePng(count));assert(!icon.isEmpty());assert.equal(icon.getSize().width,64);badgeWindow.setOverlayIcon(icon,`${count} unread`);}
  badgeWindow.flashFrame(true);badgeWindow.flashFrame(false);badgeWindow.setOverlayIcon(null,'');badgeWindow.destroy();
  assert.equal(require('../package.json').build.appId, APP_ID, 'Packaged AppUserModelID must match the window and shortcuts');
  const iconSource=path.join(root,'old-extract','icon.ico');
  fs.mkdirSync(path.dirname(iconSource),{recursive:true});
  fs.copyFileSync(path.join(__dirname,'../assets/icon.ico'),iconSource);
  const iconBytes = fs.readFileSync(iconSource);
  assert.equal(iconBytes.readUInt16LE(2), 1, 'Windows asset must be a real ICO');
  const iconSizes = new Set(Array.from({length:iconBytes.readUInt16LE(4)},(_,index) => iconBytes[6+index*16] || 256));
  assert([16,20,24,28,32,40,48,64,96,128,256].every(size=>iconSizes.has(size)), 'ICO must include taskbar and high-DPI sizes');
  const png=nativeImage.createFromPath(path.join(__dirname,'../assets/icon.png'));assert.equal(png.getSize().width,1024,'Window icon must decode at high resolution');
  const iconPath=cacheShellIcon(iconSource,app.getPath('userData'));
  fs.renameSync(path.dirname(iconSource),path.join(root,'moved-extract'));
  assert(fs.existsSync(iconPath),'Shell icon must survive a portable folder move');
  const link=path.join(root,'Daily AI.lnk');
  const other=path.join(root,'Another App.lnk');
  assert(shell.writeShortcutLink(link,'create',{target:path.join(root,'deleted-v0.1.3','Daily AI.exe'),appUserModelId:LEGACY_APP_ID,args:'--example'}));
  assert(shell.writeShortcutLink(other,'create',{target:path.join(root,'Other.exe'),appUserModelId:'other.app'}));
  const executable=process.execPath;
  const options={shell,files:[link,other],executable,iconPath};
  assert.deepEqual(repairExistingShortcuts(options),[link]);
  const repaired=shell.readShortcutLink(link);
  assert.equal(repaired.target,executable);
  assert.equal(repaired.icon,iconPath);
  assert.equal(repaired.appUserModelId,APP_ID);
  assert.equal(repaired.args,'--example');
  assert.equal(shell.readShortcutLink(other).appUserModelId,'other.app');
  assert.deepEqual(repairExistingShortcuts(options),[]);
  const win=new BrowserWindow({show:false,icon:png});win.setIcon(png);
  win.setAppDetails({appId:APP_ID,appIconPath:iconPath,appIconIndex:0,relaunchCommand:`"${executable}"`,relaunchDisplayName:'Daily AI'});
  const hwnd=win.getNativeWindowHandle().readBigUInt64LE().toString();
  const {stdout}=await promisify(execFile)('powershell',['-NoProfile','-File',path.join(__dirname,'read-taskbar-properties.ps1'),'-Handle',hwnd],{windowsHide:true,timeout:15000});
  const properties=JSON.parse(stdout.trim());
  assert.equal(properties.appId,APP_ID);
  assert.equal(properties.iconResource,`${iconPath},0`);
  assert.equal(properties.relaunchCommand,`"${executable}"`);
  assert.equal(properties.displayName,'Daily AI');
  console.log(JSON.stringify({staleShortcutRepaired:true,unrelatedShortcutPreserved:true,idempotent:true,iconSurvivesMove:true,taskbarProperties:properties}));
  win.destroy();app.quit();
}).catch(error=>{console.error(error);app.exit(1)});
