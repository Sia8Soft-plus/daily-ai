const { contextBridge, ipcRenderer } = require('electron');

const invoke = (channel, payload) => ipcRenderer.invoke(channel, payload);
contextBridge.exposeInMainWorld('dailyAI', Object.freeze({
  updateHealthy:()=>invoke('update:healthy'),
  updateState:()=>invoke('update:state'),
  checkUpdate:()=>invoke('update:check'),
  downloadUpdate:()=>invoke('update:download'),
  cancelUpdate:()=>invoke('update:cancel'),
  installUpdate:()=>invoke('update:install'),
  onUpdate:callback=>{const listener=(_event,state)=>callback(state);ipcRenderer.on('update:state',listener);return ()=>ipcRenderer.removeListener('update:state',listener);},
  shareState:id=>invoke('share:state',{id}),
  listShares:()=>invoke('share:list'),
  createShare:b=>invoke('share:create',b),
  revokeShare:id=>invoke('share:revoke',{id}),
  accountActivity:()=>invoke('account:activity'),
  accountState:()=>invoke('account:state'),
  accountUsage:()=>invoke('account:usage'),
  accountLogin:b=>invoke('account:login',b),
  accountRegister:b=>invoke('account:register',b),
  accountCaptcha:()=>invoke('account:captcha'),
  accountLogout:()=>invoke('account:logout'),
  accountMode:mode=>invoke('account:mode',{mode}),
  accountPreview:b=>invoke('account:preview',b),
  accountCancelPending:()=>invoke('account:cancelPending'),
  accountOrder:b=>invoke('account:order',b),
  accountCancel:()=>invoke('account:cancel'),
  listActivity:()=>invoke('activity:list'),
  clearActivity:()=>invoke('activity:clear'),
  previewDigest:selection=>invoke('digest:preview',selection),
  createDigest:selection=>invoke('digest:create',selection),
  getDashboardStats:()=>invoke('dashboard:getStats'),
  readActivity:id=>invoke('activity:read',{id}),
  previewCleanup:before=>invoke('cleanup:preview',{before}),
  runCleanup:before=>invoke('cleanup:run',{before}),
  confirmQuit:()=>invoke('window:confirmQuit'),
  cancelQuit:()=>invoke('window:cancelQuit'),
  onQuitRequest:callback=>{const listener=()=>callback();ipcRenderer.on('window:requestQuit',listener);return ()=>ipcRenderer.removeListener('window:requestQuit',listener);},
  onActivity:callback=>{const listener=(_event,rows)=>callback(rows);ipcRenderer.on('activity:changed',listener);return ()=>ipcRenderer.removeListener('activity:changed',listener);},
  onActivityOpen:callback=>{const listener=()=>callback();ipcRenderer.on('activity:open',listener);return ()=>ipcRenderer.removeListener('activity:open',listener);},
  bootstrap: () => invoke('bootstrap:get'),
  updateSettings: settings => invoke('settings:update', settings),
  getScheduleStatus: () => invoke('schedule:getStatus'),
  listReports: () => invoke('reports:list'),
  markReportRead: id => invoke('reports:markRead',{id}),
  revealReport: id => invoke('reports:reveal', { id }),
  getReportContent: id => invoke('reports:getContent', { id }),
  translateReportTexts: (id, language, texts) => invoke('reports:translateTexts', { id, language, texts }),
  saveBilingualReport: payload => invoke('reports:saveBilingual', payload),
  toggleFavorite: id => invoke('reports:toggleFavorite', { id }),
  listTrash: () => invoke('reports:trash:list'),
  emptyTrash: () => invoke('reports:emptyTrash'),
  chooseDataDirectory: () => invoke('storage:chooseDirectory'),
  migrateData: target => invoke('storage:migrate',{target}),
  onMigrationProgress: callback => {
    const listener=(_event,value)=>callback(value);
    ipcRenderer.on('storage:progress',listener);
    return ()=>ipcRenderer.removeListener('storage:progress',listener);
  },
  trashReport: id => invoke('reports:trash', { id }),
  restoreReport: id => invoke('reports:restore', { id }),
  deleteReportForever: id => invoke('reports:deleteForever', { id }),
  listTopics: () => invoke('topics:list'),
  addTopic: topic => invoke('topics:add', topic),
  updateTopic: (id, topic) => invoke('topics:update', { id, ...topic }),
  deleteTopic: id => invoke('topics:delete', { id }),
  setTopicEnabled: (id, enabled) => invoke('topics:setEnabled', { id, enabled }),
  saveTabs: tabs => invoke('tabs:saveState', tabs),
  listModels: () => invoke('models:list'),
  discoverModels: profile => invoke('models:discover', profile),
  modelCatalog: () => invoke('models:catalog'),
  testAndSaveModel: profile => invoke('models:testAndSave', profile),
  createReport: () => invoke('generation:create'),
  cancelGeneration: () => invoke('generation:cancel'),
  getGenerationState: () => invoke('generation:getState'),
  getSearchConfig:()=>invoke('search:getConfig'),
  saveSearchConfig:apiKey=>invoke('search:saveConfig',{apiKey}),
  onGenerationProgress: callback => {
    const listener = (_event, value) => callback(value);
    ipcRenderer.on('generation:progress', listener);
    return () => ipcRenderer.removeListener('generation:progress', listener);
  },
  setTheme: theme => invoke('theme:set', theme),
  openExternal: url => invoke('shell:openExternal', { url }),
  windowMinimize: () => invoke('window:minimize'),
  windowToggleMaximize: () => invoke('window:toggleMaximize'),
  windowClose: () => invoke('window:close')
}));
